def normalize_dtc_code(value: str) -> str:
    return value.strip().upper().replace(" ", "")


def diagnose_warning(dtc_code: str, pid_values: dict[str, Any] | None = None) -> dict[str, Any]:
    """Return five ranked causes and repair estimates for a diagnostic code."""

    normalized_code = normalize_dtc_code(dtc_code)
    diagnosis = deepcopy(DIAGNOSTIC_CATALOG.get(normalized_code, GENERIC_DIAGNOSIS))
    diagnosis["dtc_code"] = normalized_code or "UNKNOWN"
    diagnosis["pid_values"] = dict(pid_values or {})
    diagnosis["disclaimer"] = (
        "예상 원인과 견적은 참고용이며 차종, 부품 등급, 정비소와 실제 점검 결과에 따라 달라질 수 있습니다."
    )
    return diagnosis
